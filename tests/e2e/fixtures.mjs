/** 按轮次取几段正文素材（轮流取，保证相邻几轮不同；素材不够时不重复） */
export function narrative(pack, round, count = 12) {
  const pool = POOLS[pack] ?? ZHONGLOU;
  const out = [];
  for (let i = 0; i < Math.min(count, pool.length); i++) out.push(pool[(round * 3 + i) % pool.length]);
  return out.join('\n\n');
}

